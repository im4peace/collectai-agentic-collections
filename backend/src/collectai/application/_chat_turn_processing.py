"""One turn's classify-and-respond orchestration (E6-S1; extended by E6-S2/
E6-S3 for proposal creation and by E7-S1 for real escalation-case creation),
split out of `chat_flow.py` to keep that module under the code-gen skill's
300-line block threshold. `chat_flow.process_customer_message` is the only
caller. Classification itself and its unclassifiable-fallback response live
in the sibling `_chat_classification.py` module.
"""

